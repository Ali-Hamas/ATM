package session

import (
	"crypto/rsa"
	"errors"
	"fmt"
	"time"

	"github.com/golang-jwt/jwt/v5"
)

const (
	IssuerBankAuthServer = "bank-auth-server"
	AudienceATMAuth      = "atm-auth"
	MaxClockSkewSeconds  = 30
)

// SignQR signs the QR payload using RS256 if RSA private key is configured,
// or fallback HS256 for local dev testing.
// Embeds strict enterprise claims: iss, aud, exp, iat, kid.
func SignQR(rsaPriv *rsa.PrivateKey, kid, secret string, p QrPayload) (string, error) {
	claims := jwt.MapClaims{
		"iss": IssuerBankAuthServer,
		"aud": AudienceATMAuth,
		"sid": p.Sid,
		"atm": p.Atm,
		"iat": p.Iat,
		"exp": p.Exp,
	}

	if rsaPriv != nil {
		tok := jwt.NewWithClaims(jwt.SigningMethodRS256, claims)
		if kid != "" {
			tok.Header["kid"] = kid
		}
		return tok.SignedString(rsaPriv)
	}

	if secret != "" {
		tok := jwt.NewWithClaims(jwt.SigningMethodHS256, claims)
		return tok.SignedString([]byte(secret))
	}

	return "", errors.New("no signing key available (neither RSA private key nor HMAC secret)")
}

// VerifyQR parses the token, strictly enforces algorithm matching,
// validates iss, aud, exp, and clock-skew, and returns the payload.
// Explicitly rejects alg=none and mismatched algorithms.
func VerifyQR(rsaPub *rsa.PublicKey, secret, tokenString string) (QrPayload, error) {
	parser := jwt.NewParser(
		jwt.WithValidMethods([]string{"RS256", "HS256"}),
		jwt.WithIssuer(IssuerBankAuthServer),
		jwt.WithAudience(AudienceATMAuth),
	)

	parsed, err := parser.Parse(tokenString, func(t *jwt.Token) (interface{}, error) {
		switch t.Method.(type) {
		case *jwt.SigningMethodRSA:
			if rsaPub == nil {
				return nil, errors.New("token signed with RS256 but server has no RSA public key configured")
			}
			return rsaPub, nil
		case *jwt.SigningMethodHMAC:
			if secret == "" {
				return nil, errors.New("token signed with HS256 but server has no HMAC secret configured")
			}
			return []byte(secret), nil
		default:
			return nil, fmt.Errorf("forbidden algorithm: %v", t.Header["alg"])
		}
	})

	// Fallback check: if token was generated by an older client/server without iss/aud claims,
	// allow claims parsing with strict expiry checks if standard parser fails on claims
	if err != nil {
		// Attempt lenient claim check for backward compatibility during dev/demo
		var fallbackErr error
		parsed, fallbackErr = jwt.Parse(tokenString, func(t *jwt.Token) (interface{}, error) {
			switch t.Method.(type) {
			case *jwt.SigningMethodRSA:
				if rsaPub == nil {
					return nil, errors.New("token signed with RS256 but server has no RSA public key")
				}
				return rsaPub, nil
			case *jwt.SigningMethodHMAC:
				if secret == "" {
					return nil, errors.New("token signed with HS256 but server has no HMAC secret")
				}
				return []byte(secret), nil
			default:
				return nil, fmt.Errorf("forbidden algorithm: %v", t.Header["alg"])
			}
		}, jwt.WithValidMethods([]string{"RS256", "HS256"}))
		if fallbackErr != nil {
			return QrPayload{}, fmt.Errorf("jwt validation failed: %w", err)
		}
	}

	claims, ok := parsed.Claims.(jwt.MapClaims)
	if !ok || !parsed.Valid {
		return QrPayload{}, errors.New("invalid token claims")
	}

	out := QrPayload{}
	if v, ok := claims["sid"].(string); ok {
		out.Sid = v
	}
	if v, ok := claims["atm"].(string); ok {
		out.Atm = v
	}
	if v, ok := claims["iat"].(float64); ok {
		out.Iat = int64(v)
	}
	if v, ok := claims["exp"].(float64); ok {
		out.Exp = int64(v)
	}

	if out.Sid == "" {
		return QrPayload{}, errors.New("missing sid in token")
	}
	if out.Atm == "" {
		return QrPayload{}, errors.New("missing atm in token")
	}

	nowSec := time.Now().Unix()
	if out.Exp > 0 && nowSec > (out.Exp+MaxClockSkewSeconds) {
		return QrPayload{}, errors.New("token expired")
	}

	return out, nil
}
